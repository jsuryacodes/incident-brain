"""A scripted MCP client session (no LLM) against the streamable-HTTP endpoint -> docs/mcp-transcript.md.

python -m backend.agents.mcp_transcript [--tenant kestrel_pay]

Starts the API on a free local port, connects an MCP client to http://127.0.0.1:<port>/mcp/<tenant>/, and shows what
any MCP client sees: discovery (tools, prompts, resources), the investigate_alert prompt, then tool selection done
by a fixed script that follows that prompt (the choices an LLM would make are written out as the script's reasons),
each call's result and its Cypher receipt. Read-only; the hero graph must be seeded.
"""
import argparse
import json
import socket
import threading
import time
from pathlib import Path

import anyio
import uvicorn
from mcp import Client

OUT = Path(__file__).resolve().parents[2] / "docs" / "mcp-transcript.md"


def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def serve(port):
    from backend.api.main import app
    server = uvicorn.Server(uvicorn.Config(app, host="127.0.0.1", port=port, log_level="warning"))
    threading.Thread(target=server.run, daemon=True).start()
    for _ in range(100):
        try:
            socket.create_connection(("127.0.0.1", port), timeout=0.2).close()
            return server
        except OSError:
            time.sleep(0.1)
    raise RuntimeError("API did not start")


def clip(s, n):
    return s if len(s) <= n else s[:n] + " …"


async def session(url, L):
    async with Client(url) as c:
        tools = (await c.list_tools()).tools
        prompts = (await c.list_prompts()).prompts
        res = (await c.list_resources()).resources
        L += ["## 1. Discovery", "", f"`tools/list` → **{len(tools)} tools** (read-only):", ""]
        L += [f"- `{t.name}`: {clip(t.description, 140)}" for t in tools]
        L += ["", f"`prompts/list` → " + ", ".join(f"`{p.name}`" for p in prompts),
              f"`resources/list` → " + ", ".join(f"`{r.uri}`" for r in res), ""]
        g = await c.get_prompt("investigate_alert", {"service": "svc:payments-api",
                                                     "symptom": "5xx rate 12% and p99 4.1s for the last 15 minutes"})
        L += ["## 2. The prompt a client starts from", "", "`prompts/get investigate_alert`:", "",
              "> " + g.messages[0].content.text, ""]
        L += ["## 3. Tool selection and receipts", "",
              "No LLM here: a fixed script follows the prompt and picks each next tool from the previous result. The "
              "reason for each choice is written above the call.", ""]
        plan = [("recent_changes", {"since_minutes": 120}, "every recent change in the company is a lead"),
                ("recent_changes_downstream", {"service_id": "svc:payments-api", "since_minutes": 120, "max_hops": 6},
                 "which lead is on the alerting service's call path?")]
        n = 0
        while plan:
            name, args, why = plan.pop(0)
            r = await c.call_tool(name, args)
            n += 1
            sc = r.structured_content or {}
            out, rec = sc.get("result", {}), sc.get("receipt", {})
            L += [f"### {n}. `{name}`", "", f"*Why:* {why}", "", "```json", json.dumps(args), "```", "",
                  "Result (excerpt):", "", "```json", clip(json.dumps(out, ensure_ascii=False), 700), "```", "",
                  "Cypher receipt:", ""]
            for q in rec.get("queries", [])[:3]:
                L += ["```cypher", q["cypher"], "```", f"params `{clip(json.dumps(q['params'], default=str), 200)}`", ""]
            if name == "recent_changes_downstream" and out.get("hits"):
                h = out["hits"][0]
                plan += [("who_to_call", {"service_id": h["service"]}, f"the nearest hit is {h['service']}: who knows it?"),
                         ("rollback_safety", {"deploy_id": h["deploy"]["id"]}, "before recommending a rollback: is it safe?")]
    return n


def main():
    ap = argparse.ArgumentParser(prog="python -m backend.agents.mcp_transcript")
    ap.add_argument("--tenant", default="kestrel_pay")
    a = ap.parse_args()
    port = free_port()
    server = serve(port)
    url = f"http://127.0.0.1:{port}/mcp/{a.tenant}/"
    L = ["# MCP transcript: discovery → selection → receipts", "",
         "> Generated by `python -m backend.agents.mcp_transcript` (a scripted client, no LLM) against the "
         f"streamable-HTTP endpoint `/mcp/{a.tenant}/` of the running API. Every call returns the tool's JSON plus the "
         "exact parameterised Cypher it ran (also as structuredContent).", ""]
    try:
        n = anyio.run(session, url, L)
    finally:
        server.should_exit = True
    L += ["## 4. The same through our own agents", "",
          "`python -m backend.agents.firefighter --service svc:payments-api --symptom \"5xx\" --tools-via mcp` runs the "
          "Firefighter with its tool list and every call coming through an MCP client session to this server; "
          "`tests/test_mcp.py::test_tools_via_mcp_parity` checks it produces the same steps, results and report as direct calls.", ""]
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT} ({n} tool calls over MCP)")


if __name__ == "__main__":
    main()
